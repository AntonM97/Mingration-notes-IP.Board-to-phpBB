    public static void processTheOutput(String output) {
        Pattern pattern = Pattern.compile(
                "SELECT\\s+COUNT\\(\\*\\)\\s+FROM\\s+([a-zA-Z0-9_]+);[\\s\\S]*?\\|\\s*(\\d+)\\s*\\|"
        );

        Matcher matcher = pattern.matcher(output);

        List<String> names = new ArrayList<>();
        List<String> counts = new ArrayList<>();

        while (matcher.find()) {
                 counts.add(matcher.group(2)); // count
                 names.add(matcher.group(1));  // table name
        }
        
        names.forEach(r ->System.out.println(r));
        
        counts.forEach(r->System.out.println(r));
    }
    
